-- ผ่อนมาตรการเข้าสู่ระบบของวิทยาลัยตัวอย่าง — เฉพาะตอนพัฒนา
--
--   psql -v ON_ERROR_STOP=1 -f api/tools/demo-auth-relax.sql vecsms_api_test
--
-- ─── ทำไมถึงต้องมีไฟล์นี้ ───
-- ตอนไล่กดดูหน้าจอทีละหน้า มาตรการที่ถูกต้องในระบบจริงกลายเป็นตัวขวาง:
--   · ยืนยันสองชั้นของ admin/director ต้องเปิดแอป authenticator ทุกครั้ง
--   · การผูกอุปกรณ์ทำให้เปิดแอปในเบราว์เซอร์ที่สองแล้วติด "รออนุมัติ"
--   · ใส่รหัสผิดห้าครั้งแล้วบัญชีถูกล็อก 15 นาที ระหว่างที่ยังจำรหัสไม่ได้
--   · token อายุ 30 นาที เด้งออกกลางการกรอกฟอร์ม
--
-- ─── นี่คือการปิดมาตรการโดยรู้ตัว ไม่ใช่การแก้บั๊ก ───
-- ทุกค่าที่นี่อยู่ใน `auth_policy` ซึ่งเป็น**ข้อมูลรายวิทยาลัย** ไม่ใช่โค้ด
-- จึงไม่มีบรรทัดไหนของระบบถูกทำให้อ่อนลง และไม่มีอะไรติดไปกับ deploy
-- ย้อนกลับด้วย demo-auth-strict.sql ข้าง ๆ ไฟล์นี้ ซึ่งคืนค่าเป็น
-- `default` ของคอลัมน์ตรง ๆ จึงไม่มีวันเพี้ยนจากค่าจริงใน migration
--
-- ─── สิ่งที่ไฟล์นี้ปิดไม่ได้ และไม่ควรพยายามปิด ───
-- บัญชีฝั่งผู้ให้บริการ (`platform_user`) บังคับยืนยันสองชั้นที่ชั้นโค้ด
-- โดยไม่มีสวิตช์ — เพราะบัญชีชุดนั้นเห็นตัวเลขธุรกิจของทุกวิทยาลัยและ
-- เปิด/ระงับวิทยาลัยได้ ใช้ TOTP secret ที่ seed ไว้แทน
--
-- ─── ครอบคลุมกว่า demo-mfa-off.sql ───
-- ไฟล์นั้นแก้เฉพาะ require_mfa_roles สำหรับกรณีเฉพาะคือ "บูตมาโดยไม่มี
-- MFA_SECRET_KEY แล้วเข้าไม่ได้เลย" ส่วนไฟล์นี้ผ่อนทั้งชุดเพื่อการกดดูหน้าจอ
-- ═══════════════════════════════════════════════════════════════════
\set ON_ERROR_STOP on

-- ─── ด่านตรวจ ───
-- รายชื่อฐานตรงกับ SAFE_DATABASES ใน seed-demo-users.cjs — เป็น**รายชื่อ**
-- ไม่ใช่สวิตช์ เพราะสวิตช์แบบ FORCE=1 กดผ่านได้ด้วยความเคยชิน
do $$
begin
  if current_database() not in ('vecsms_api_test', 'vecsms_dev', 'vecsms_demo') then
    raise exception
      'ฐาน "%" ไม่ใช่ฐานสำหรับพัฒนา — ไฟล์นี้ถอดการยืนยันสองชั้นและการอนุมัติอุปกรณ์',
      current_database();
  end if;
end $$;

begin;

update auth_policy set
  -- ยืนยันสองชั้น: admin/director เข้าด้วยรหัสผ่านอย่างเดียว
  require_mfa_roles    = '{}',

  -- การอนุมัติอุปกรณ์: เปิดแอปกี่เบราว์เซอร์กี่เครื่องก็ได้
  -- (แถวเดิมใน device_binding ไม่ต้องลบ เพราะเมื่อปิดค่านี้ ขั้นตรวจถูกข้ามทั้งก้อน)
  bind_student_device  = false,
  max_devices_student  = 99,

  -- การล็อกบัญชีเมื่อใส่รหัสผิด
  max_failed_attempts  = 1000,
  lockout_minutes      = 1,

  -- การบล็อกตามไอพี — เครื่องพัฒนาเครื่องเดียวยิงทุกคำขอ จึงชนเพดานเร็วมาก
  max_ip_attempts      = 10000,
  ip_window_minutes    = 1,
  ip_block_minutes     = 1,

  -- อายุ token: 30 นาทีสั้นกว่าช่วงที่นั่งกดดูหน้าจอต่อเนื่อง
  access_token_minutes = 480,

  -- ขอรหัสรีเซ็ตซ้ำได้ ไม่งั้นทดสอบหน้าลืมรหัสผ่านได้วันละสามครั้ง
  max_reset_per_day    = 1000,
  max_reset_per_ip_day = 1000,
  reset_code_attempts  = 100,

  -- 20 คือเพดานที่ constraint ยอม ไม่ใช่ค่าที่เลือกเอง — สคีมาไม่ยอมให้
  -- ตั้งค่าที่ทำให้เดารหัสหกหลักได้ไม่จำกัด แม้จะเป็นคนตั้งค่าเองก็ตาม
  mfa_max_attempts     = 20
where institution_id = '11111111-1111-1111-1111-111111111111';

-- ปลดล็อกบัญชีที่ค้างอยู่จากการลองรหัสก่อนหน้านี้
update user_credential
   set locked_until = null, failed_attempts = 0
 where institution_id = '11111111-1111-1111-1111-111111111111'
   and (locked_until is not null or failed_attempts > 0);

commit;

