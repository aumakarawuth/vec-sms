import { types } from 'pg';

/**
 * ปรับวิธีแปลงชนิดข้อมูลของ PostgreSQL ก่อนเปิดการเชื่อมต่อใด ๆ
 *
 * ─── ปัญหาที่แก้: วันที่เลื่อนไปหนึ่งวัน ───
 * ค่าเริ่มต้นของไลบรารี pg แปลงชนิด date เป็น JavaScript Date โดยตีความว่าเป็น
 * เที่ยงคืนตามเขตเวลาของเครื่อง เมื่อแปลงกลับเป็น ISO เพื่อส่งเป็น JSON
 * ค่าจะถูกแปลงเป็น UTC ทำให้วันที่เลื่อนไปหนึ่งวันในเขตเวลา UTC+7
 *
 *   ในฐานข้อมูล  2026-05-13
 *   Date object   2026-05-13T00:00:00+07:00
 *   ที่ส่งออกไป   2026-05-12T17:00:00.000Z   ← ผิดไปหนึ่งวัน
 *
 * ระบบนี้เต็มไปด้วยวันที่ที่พลาดไม่ได้ — วันครบกำหนดชำระ วันที่สอน วันเกิด
 * วันที่ในเอกสารราชการ การเลื่อนหนึ่งวันทำให้เรียกเก็บเงินผิดวัน
 * และทำให้คาบเรียนหายไปจากตารางของนักศึกษา
 *
 * ชนิด date ไม่มีเวลาและไม่มีเขตเวลาอยู่แล้ว จึงส่งต่อเป็นสตริง YYYY-MM-DD
 * ตามที่ฐานข้อมูลเก็บไว้จริง
 */
export function configurePgTypes(): void {
  const DATE_OID = 1082;
  types.setTypeParser(DATE_OID, (value: string) => value);

  // numeric ยังคงเป็นสตริงตามค่าเริ่มต้นของ pg โดยตั้งใจ
  // เพราะ numeric ของ PostgreSQL มีความละเอียดมากกว่า double ของ JavaScript
  // การแปลงเป็น number จะทำให้จำนวนเงินคลาดเคลื่อนในหลักสตางค์
  // ฝั่งผู้เรียกต้องแปลงเองเมื่อจำเป็น
}
