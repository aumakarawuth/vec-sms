import { createHmac, randomBytes } from 'node:crypto';

/**
 * รหัสรีเซ็ตรหัสผ่าน — สร้าง ทำให้เป็นรูปแบบมาตรฐาน และแฮชด้วยกุญแจ
 *
 * ─── ทำไมรหัสสั้นที่คนอ่านออก ไม่ใช่ token ยาว ๆ ในลิงก์ ───
 * นักศึกษาอาชีวะจำนวนมากไม่มีอีเมลของตัวเองตอนเข้าเรียน (เหตุผลเดียวกับที่
 * ชื่อผู้ใช้เป็นรหัสประจำตัวไม่ใช่อีเมล) ทางที่ครอบคลุมทุกคนคือรหัสที่
 * เจ้าหน้าที่อ่านให้ฟังทางโทรศัพท์ได้ หรือส่ง SMS ได้ ซึ่งต้องสั้นและ
 * ไม่มีตัวอักษรที่ฟังแล้วสับสน
 *
 * ─── ชุดอักขระ ───
 * ตัด I L O 0 1 ออกทั้งหมด เพราะเป็นคู่ที่อ่านให้ฟังทางโทรศัพท์แล้วผิดบ่อย
 * ที่สุด และการผิดหนึ่งตัวหมายถึงเสียโควตาการกรอกไปหนึ่งครั้งจากห้าครั้ง
 * เหลือ 31 ตัว × 8 ตำแหน่ง ≈ 39.6 บิต ซึ่งเดาสุ่มไม่ได้ในโควตาห้าครั้ง
 *
 * ─── ทำไมแฮชด้วยกุญแจ ไม่ใช่ sha256 เปล่า ๆ ───
 * รหัส 39.6 บิตที่แฮชด้วย sha256 เปล่า ๆ ไล่เดาทุกความเป็นไปได้จนเจอ
 * ได้ในเวลาระดับนาทีด้วยการ์ดจอใบเดียว ถ้าฐานข้อมูลรั่ว ตารางนี้จะกลาย
 * เป็นจุดที่อ่อนที่สุดของทั้งระบบ ทั้งที่ user_credential ข้าง ๆ กันแฮช
 * ด้วย scrypt อย่างแน่นหนา — การใส่กุญแจที่อยู่นอกฐานข้อมูลปิดช่องนี้
 * หลักเดียวกับที่ ip_hash ใช้ IP_HASH_SECRET อยู่แล้ว
 */

const ALPHABET = 'ABCDEFGHJKMNPQRSTUVWXYZ23456789';
const CODE_LENGTH = 8;

/**
 * สุ่มรหัสใหม่ในรูปแบบ XXXX-XXXX
 *
 * ใช้การสุ่มซ้ำเมื่อได้ค่าที่ทำให้การแจกแจงเอียง (rejection sampling)
 * ไม่ใช่ byte % 31 ตรง ๆ เพราะ 256 หารด้วย 31 ไม่ลงตัว ตัวอักษรแปดตัวแรก
 * ของชุดจึงมีโอกาสออกมากกว่าตัวอื่น ๆ ราว 3% ซึ่งลดความแข็งแรงของรหัสลง
 */
export function generateResetCode(): string {
  const limit = 256 - (256 % ALPHABET.length);
  const out: string[] = [];

  while (out.length < CODE_LENGTH) {
    for (const b of randomBytes(CODE_LENGTH)) {
      if (b >= limit) continue;
      out.push(ALPHABET[b % ALPHABET.length]);
      if (out.length === CODE_LENGTH) break;
    }
  }

  return `${out.slice(0, 4).join('')}-${out.slice(4).join('')}`;
}

/**
 * ทำให้รหัสที่ผู้ใช้พิมพ์เข้ามาอยู่ในรูปแบบเดียวกับตอนแฮช
 *
 * ตัดขีดคั่นและช่องว่างออก แล้วเปลี่ยนเป็นตัวพิมพ์ใหญ่ เพราะคนพิมพ์
 * ตามที่เห็นบ้าง ตามที่ได้ยินบ้าง และแป้นพิมพ์บนมือถือมักขึ้นตัวพิมพ์เล็ก
 * ให้เอง การไม่รองรับตรงนี้ทำให้คนกรอกถูกแต่ระบบบอกว่าผิด
 */
export function normalizeResetCode(raw: string): string {
  return raw.replace(/[\s-]/g, '').toUpperCase();
}

/**
 * กุญแจสำหรับแฮชรหัสรีเซ็ต แยกสายจาก JWT_SECRET ด้วยป้ายกำกับ
 *
 * ไม่ใช้ JWT_SECRET ตรง ๆ เพราะการใช้กุญแจเดียวกันสองหน้าที่ทำให้ค่าที่
 * รั่วจากที่หนึ่งใช้โจมตีอีกที่ได้ทันที — เป็นข้อผิดพลาดเดียวกับที่
 * production-guard ห้ามไม่ให้ JWT_SECRET เท่ากับ IP_HASH_SECRET
 *
 * ที่ไม่เพิ่มตัวแปรสภาพแวดล้อมใหม่ เพราะกุญแจที่ต้องตั้งเองเพิ่มอีกตัว
 * คือกุญแจที่มีโอกาสถูกลืมตั้งแล้วตกไปใช้ค่าเริ่มต้นที่เดาได้ ส่วนการ
 * แตกสายด้วยป้ายกำกับให้ผลเทียบเท่าโดยไม่เพิ่มสิ่งที่ต้องตั้ง
 */
export function resetCodeKey(secret: string): Buffer {
  return createHmac('sha256', secret).update('vec-sms:password-reset').digest();
}

export function hashResetCode(code: string, secret: string): Buffer {
  return createHmac('sha256', resetCodeKey(secret))
    .update(normalizeResetCode(code))
    .digest();
}
